"""
Stage 0 - Landing: the synthetic insurer's source systems drop one business date's files.

  garages       garage network register (CSV, day 1)
  policy_admin  policies (CSV full extract day 1, then Debezium-style CDC JSON lines), clauses
  bureau        credit bureau profiles (PSV + trailer T|count|sum; full day 1, ~5 % deltas later)
  claims        claim snapshots and status events (JSON lines)
  telematics    crash events (JSON lines; the live feed streams through Kafka instead)

Every <landing>/<source>/<date>/ folder gets _manifest.json (file, entity, records, size,
sha256, control total as the source reports them). Generated by generators/ from one seeded
universe; planted faults are listed in generators/landing.py.

Usage:
  spark-submit land_sources.py --business-date 2026-10-12 [--landing URI]
  python cde/jobs/land_sources.py --all-dates --landing data/landing      # laptop, no Spark
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import mcc_common as C  # noqa: E402

from generators.landing import files_for  # noqa: E402
from generators.universe import World  # noqa: E402


def parser():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--business-date", type=C.parse_date)
    p.add_argument("--all-dates", action="store_true")
    p.add_argument("--landing", default=C.DEFAULT_LANDING)
    p.add_argument("--sources", default="", help="comma-separated subset of sources")
    p.add_argument("--db-prefix", default=C.DEFAULT_PREFIX)
    p.add_argument("--pipeline-run", default=None)
    return p


def land(fs, landing: str, world: World, business_date, sources=None) -> dict:
    out = {}
    for source, files in files_for(world, business_date).items():
        if sources and source not in sources:
            continue
        folder = f"{landing}/{source}/{business_date.isoformat()}"
        fs.delete(folder)
        for name, data in files.items():
            fs.write_bytes(f"{folder}/{name}", data)
        out[source] = (len(files) - 1, sum(len(b) for n, b in files.items() if n != "_manifest.json"))
        print(f"  {source:<13} {out[source][0]:>2} files {out[source][1] / 1e6:7.2f} MB -> {folder}", flush=True)
    return out


def main(argv=None, spark=None) -> int:
    args, _ = parser().parse_known_args(argv)
    if not args.all_dates and args.business_date is None:
        raise SystemExit("--business-date or --all-dates is required")
    landing = args.landing.rstrip("/")
    if "://" not in landing:
        landing = str(Path(landing).resolve())
    if spark is None and not landing.startswith(("/", "file:")):
        spark = C.get_spark("mcc-land-sources")
    fs = C.filesystem(spark, landing)
    dates = [C.parse_date(d) for d in C.CFG["business_dates"]] if args.all_dates else [args.business_date]
    sources = [s for s in args.sources.split(",") if s] or None
    world = World()
    for d in dates:
        print(f"landing {d}", flush=True)
        land(fs, landing, world, d, sources)
    return 0


if __name__ == "__main__":
    sys.exit(main())
